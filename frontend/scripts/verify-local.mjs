import { chromium } from 'playwright'

const browser = await chromium.launch({ executablePath: 'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe', headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 })
const errors = []
page.on('pageerror', error => { errors.push(error.message); console.log('PAGEERROR', error.stack) })
await page.goto('http://127.0.0.1:5173/', { waitUntil: 'networkidle' })
await page.getByText('Survey aircraft 01').first().waitFor()
await page.getByText('ADAPTER ONLY').waitFor()
await page.screenshot({ path: '../docs/geospatial/local-browser.png', fullPage: true })
await page.getByRole('textbox', { name: 'Search assets' }).fill('depot')
if (await page.locator('.ws-asset').count() !== 1) errors.push('Asset search did not filter')
await page.getByRole('textbox', { name: 'Search assets' }).fill('')
await page.getByRole('button', { name: /County boundaries/ }).click()
if (await page.getByRole('button', { name: /County boundaries/ }).getAttribute('aria-pressed') !== 'true') errors.push('County layer toggle failed')
await page.getByRole('button', { name: /Terrain/ }).click()
await page.waitForTimeout(1200)
await page.screenshot({ path: '../docs/geospatial/local-browser-terrain.png', fullPage: true })
await page.getByRole('button', { name: /Globe/ }).click()
await page.waitForTimeout(1200)
await page.screenshot({ path: '../docs/geospatial/local-browser-globe.png', fullPage: true })
await page.getByRole('button', { name: /^Map$/ }).click()
await page.getByRole('button', { name: 'Environment', exact: true }).click()
await page.getByRole('button', { name: /Stockholm/ }).click()
await page.locator('.ws-weather-title').waitFor()
await page.getByText('WIND SPEED').waitFor()
if (!/\d+(?:\.\d+)? m\/s/.test(await page.locator('.ws-weather-metrics').innerText())) errors.push('Live wind metric missing')
await page.waitForTimeout(1500)
await page.screenshot({ path: '../docs/geospatial/local-browser-weather.png', fullPage: true })
await page.getByRole('button', { name: 'Layers', exact: true }).click()
await page.getByRole('button', { name: 'ASSET', exact: true }).click()
await page.getByRole('button', { name: /Sector Alpha survey/ }).click()
const before = await page.locator('.ws-consequence').innerText()
const revisionBeforePreview = await page.locator('.ws-top-revision').innerText()
await page.getByRole('button', { name: 'Preview fault impact' }).click()
await page.getByText('WHAT IF / FAULT / uav-01').waitFor()
if (!(await page.locator('.ws-consequence').innerText()).includes('UNAVAILABLE')) errors.push('Preview did not compute service consequence')
if (await page.locator('.ws-top-revision').innerText() !== revisionBeforePreview) errors.push('Preview changed world revision')
await page.waitForTimeout(1200)
await page.screenshot({ path: '../docs/geospatial/local-browser-preview.png', fullPage: true })
await page.getByRole('button', { name: 'Exit preview' }).click()
await page.locator('.ws-consequence.available').waitFor()
await page.getByRole('button', { name: 'Record fault' }).click()
await page.locator('.ws-consequence.unavailable').waitFor()
const after = await page.locator('.ws-consequence').innerText()
await page.screenshot({ path: '../docs/geospatial/local-browser-fault.png', fullPage: true })
await page.getByRole('slider', { name: 'World revision' }).fill('1')
await page.locator('.ws-consequence.available').waitFor()
const replay = await page.locator('.ws-consequence').innerText()
await page.getByRole('button', { name: 'Return to latest' }).click()
await page.locator('.ws-consequence.unavailable').waitFor()
await page.getByRole('button', { name: 'Record repair' }).click()
await page.locator('.ws-consequence.available').waitFor()
console.log(JSON.stringify({ before, after, replay, errors, screenshots: ['local-browser.png', 'local-browser-terrain.png', 'local-browser-globe.png', 'local-browser-weather.png', 'local-browser-preview.png', 'local-browser-fault.png'] }))
const offlinePage = await browser.newPage({ viewport: { width: 1440, height: 900 } })
offlinePage.on('pageerror', error => errors.push(error.message))
await offlinePage.route('https://tiles.openfreemap.org/**', route => route.abort())
await offlinePage.goto('http://127.0.0.1:5173/', { waitUntil: 'networkidle' })
await offlinePage.getByText('LOCAL MODE').waitFor({ timeout: 15000 })
await offlinePage.screenshot({ path: '../docs/geospatial/local-browser-fallback.png', fullPage: true })
console.log(JSON.stringify({ offlineFallback: 'passed', errors }))
await browser.close()
if (errors.length || !before.includes('AVAILABLE') || !after.includes('UNAVAILABLE') || !replay.includes('AVAILABLE')) process.exitCode = 1
